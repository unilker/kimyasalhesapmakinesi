"""Generates lib/core/thermo_data.dart from the tables in tool/data.

  python3 tool/gen_thermo.py

CODATA key values come first; the supplementary table only adds substances
that CODATA does not list (see the header of each TSV for sources and the
checks every row passed).
"""
import re

NOTES = {
    'graphite': 'grafit', 'rhombic': 'rombik', 'white': 'beyaz', 'corundum': 'korund',
    'alpha quartz': 'α-kuvars', 'rutile': 'rutil', 'red': 'kırmızı', 'tetragonal': 'tetragonal',
    'gamma': 'γ', 'undissoc.': 'iyonlaşmamış', 'glucose': 'glikoz', 'calcite': 'kalsit',
    'aragonite': 'aragonit', 'lactic acid': 'laktik asit', 'red or litharge': 'kırmızı, litarj',
    'yellow or massicot': 'sarı, masikot', 'cubic': 'kübik', 'hexagonal': 'hekzagonal',
    'gray': 'gri', 'sphalerite': 'sfalerit',
}


def charge_text(z):
    if z == 0:
        return ''
    n = abs(z)
    return '^' + ('' if n == 1 else str(n)) + ('+' if z > 0 else '-')


def read(path):
    for line in open(path, encoding='utf-8'):
        if line.startswith('#') or not line.strip():
            continue
        yield line.rstrip('\n').split('\t')


def codata():
    for sub, state, h, uh, s, us in read('tool/data/codata_key_values.tsv'):
        if '/' in sub:  # CdSO4·8/3H2O: fractional hydrate, not parseable
            continue
        f, z = sub, 0
        m = re.match(r'^(.*)\^([+-])(\d*)$', sub) or re.match(r'^(.*?)([+-])(\d*)$', sub)
        if m:
            f, z = m.group(1), (int(m.group(3)) if m.group(3) else 1) * (1 if m.group(2) == '+' else -1)
        parts = state.split(',', 1)
        st = {'cr': 's'}.get(parts[0], parts[0])
        note = parts[1].strip() if len(parts) > 1 else ''
        yield dict(formula=f.replace(' ', '') + charge_text(z), state=st, note=note,
                   h=float(h), s=float(s), uh=float(uh) if uh else 0.0, us=float(us) if us else 0.0,
                   source='CODATA')


def supplementary():
    for f, z, st, note, h, s, src, conf in read('tool/data/thermo_supplementary.tsv'):
        yield dict(formula=f + charge_text(int(z)), state=st, note=note, h=float(h), s=float(s),
                   uh=0.0, us=0.0, source={'crc': 'CRC', 'nbs': 'NBS', 'janaf': 'JANAF'}[src])


def main():
    rows = list(codata())
    # The stable form at 25 °C is offered first when a substance has several.
    preferred = {'calcite': 0, 'aragonite': 1}
    seen = {(r['formula'], r['state'], r['note']) for r in rows}
    seen_fs = {(r['formula'], r['state']) for r in rows}
    for r in sorted(supplementary(), key=lambda r: (r['formula'], r['state'], preferred.get(r['note'], 0))):
        if (r['formula'], r['state']) in seen_fs and not r['note']:
            continue
        if (r['formula'], r['state'], r['note']) in seen:
            continue
        rows.append(r)
    out = [
        '// GENERATED by tool/gen_thermo.py from tool/data/*.tsv – do not edit.',
        '// Standard molar enthalpies of formation and entropies at 298.15 K, 1 bar.',
        "part of 'thermochem.dart';",
        '',
        'const List<ThermoEntry> thermoData = [',
    ]
    for r in rows:
        note = r['note']
        tr = NOTES.get(note, note)
        if note and note not in NOTES:
            raise SystemExit('missing Turkish note for ' + note)
        out.append(
            "  ThermoEntry('%s', '%s', %r, %r, %r, %r, ThermoSource.%s%s),"
            % (r['formula'], r['state'], r['h'], r['s'], r['uh'], r['us'], r['source'].lower(),
               (", note: Bi('%s', '%s')" % (note, tr)) if note else ''))
    out.append('];')
    open('lib/core/thermo_data.dart', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
    print(len(rows), 'entries')


if __name__ == '__main__':
    main()
