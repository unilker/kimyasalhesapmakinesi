"""Generates lib/core/ksp_data.dart from tool/data/crc_ksp.tsv.

  python3 tool/gen_ksp.py

Each salt is split into its ions (cation charge from electroneutrality);
the dissolution equation is written as MₐXᵦ(s) ⇌ aMᶻ⁺ + bXʸ⁻. Left out:
sulfides and selenides (Lange data; S²⁻ is not a real solution species)
and two rows whose name and formula disagree in the source.
"""
import re

ANIONS = {  # formula: (charge, English, Turkish)
    'F': (-1, 'fluoride', 'florür'), 'Cl': (-1, 'chloride', 'klorür'), 'Br': (-1, 'bromide', 'bromür'),
    'I': (-1, 'iodide', 'iyodür'), 'OH': (-1, 'hydroxide', 'hidroksit'), 'CN': (-1, 'cyanide', 'siyanür'),
    'SCN': (-1, 'thiocyanate', 'tiyosiyanat'), 'IO3': (-1, 'iodate', 'iyodat'),
    'BrO3': (-1, 'bromate', 'bromat'), 'ClO4': (-1, 'perchlorate', 'perklorat'),
    'IO4': (-1, 'periodate', 'periyodat'), 'NO3': (-1, 'nitrate', 'nitrat'),
    'CH3CO2': (-1, 'acetate', 'asetat'), 'CO3': (-2, 'carbonate', 'karbonat'),
    'SO4': (-2, 'sulfate', 'sülfat'), 'SO3': (-2, 'sulfite', 'sülfit'), 'CrO4': (-2, 'chromate', 'kromat'),
    'C2O4': (-2, 'oxalate', 'oksalat'), 'PtCl6': (-2, 'hexachloroplatinate', 'hekzakloroplatinat'),
    'PO4': (-3, 'phosphate', 'fosfat'), 'AsO4': (-3, 'arsenate', 'arsenat'),
}
CATIONS = {
    'Aluminum': 'Alüminyum', 'Barium': 'Baryum', 'Beryllium': 'Berilyum', 'Bismuth': 'Bizmut',
    'Cadmium': 'Kadmiyum', 'Calcium': 'Kalsiyum', 'Cesium': 'Sezyum', 'Cobalt(II)': 'Kobalt(II)',
    'Copper(I)': 'Bakır(I)', 'Copper(II)': 'Bakır(II)', 'Europium(III)': 'Evropiyum(III)',
    'Gallium(III)': 'Galyum(III)', 'Iron(II)': 'Demir(II)', 'Iron(III)': 'Demir(III)',
    'Lanthanum': 'Lantan', 'Lead(II)': 'Kurşun(II)', 'Lithium': 'Lityum', 'Magnesium': 'Magnezyum',
    'Manganese(II)': 'Mangan(II)', 'Mercury(I)': 'Cıva(I)', 'Mercury(II)': 'Cıva(II)',
    'Mercury (II)': 'Cıva(II)', 'Neodymium': 'Neodimyum', 'Nickel(II)': 'Nikel(II)',
    'Palladium(II)': 'Paladyum(II)', 'Potassium': 'Potasyum', 'Praseodymium': 'Praseodimyum',
    'Rubidium': 'Rubidyum', 'Scandium': 'Skandiyum', 'Silver(I)': 'Gümüş', 'Strontium': 'Stronsiyum',
    'Thallium(I)': 'Talyum(I)', 'Thallium(III)': 'Talyum(III)', 'Tin(II)': 'Kalay(II)', 'Yttrium': 'İtriyum',
    'Zinc': 'Çinko',
}
SKIP_NAMES = ('sulfide', 'selenide', 'Lead(II)selenite')


def split(formula):
    """(cation symbol, cation count, anion formula, anion count)."""
    m = re.match(r'^([A-Z][a-z]?)(\d*)\(([A-Za-z0-9]+)\)(\d+)$', formula)
    if m:
        return m.group(1), int(m.group(2) or 1), m.group(3), int(m.group(4))
    for an in sorted(ANIONS, key=len, reverse=True):
        m = re.match(r'^([A-Z][a-z]?)(\d*)' + re.escape(an) + r'(\d*)$', formula)
        if m:
            return m.group(1), int(m.group(2) or 1), an, int(m.group(3) or 1)
    raise SystemExit('cannot split ' + formula)


def charge(z):
    return '^' + ('' if abs(z) == 1 else str(abs(z))) + ('+' if z > 0 else '-')


def ksp_value(text):
    t = text.replace('−', '-').replace('×', 'x').replace(' ', '')
    m = re.match(r'^([\d.]+)x10\^(-?\d+)$', t)
    return float('%se%s' % (m.group(1), m.group(2)))


out = ['// GENERATED by tool/gen_ksp.py from tool/data/crc_ksp.tsv – do not edit.',
       '// Solubility products at 25 °C, CRC Handbook of Chemistry and Physics, 84th ed.',
       "part of 'solubility.dart';", '', 'const List<SaltData> kspTable = [']
n = 0
for line in open('tool/data/crc_ksp.tsv', encoding='utf-8'):
    if line.startswith('#') or not line.strip():
        continue
    name, formula, ksp = line.rstrip('\n').split('\t')
    if any(s in name for s in SKIP_NAMES):
        continue
    if name.startswith('Mercury (II)'):
        cat_name, rest = 'Mercury (II)', name[len('Mercury (II) '):]
    else:
        cat_name, rest = name.split(' ', 1)
    sym, ncat, an, nan = split(formula)
    za, an_en, an_tr = ANIONS[an]
    if rest != an_en:
        raise SystemExit('name/anion mismatch: %s %s' % (name, formula))
    cation = sym
    if cat_name == 'Mercury(I)':  # Hg2²⁺ dimer
        if ncat != 2:
            raise SystemExit(formula)
        cation, ncat = 'Hg2', 1
    total = -za * nan
    if total % ncat:
        raise SystemExit('charge does not divide: ' + formula)
    zc = total // ncat
    tr = '%s %s' % (CATIONS[cat_name], an_tr)
    out.append("  SaltData(Bi('%s', '%s'), '%s', '%s', %d, '%s', %d, %r),"
               % (name.replace('Mercury (II)', 'Mercury(II)'), tr, formula, cation + charge(zc), ncat,
                  an + charge(za), nan, ksp_value(ksp)))
    n += 1
out.append('];')
open('lib/core/ksp_data.dart', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(n, 'salts')
