# Display formulas (the source's CH2O2 for formic acid, and its isobutylamine
# formula for sec-butylamine, are replaced).
FORMULA = {
    'Formic acid': 'HCOOH', 'Hydrogen peroxide': 'H2O2', 'Cyanic acid': 'HOCN', 'Oxalic acid': 'H2C2O4',
    'sec-Butylamine': 'CH3CH2CH(NH2)CH3',
}

out = ['// GENERATED by tool/gen_pka.py from tool/data/crc_pka.tsv – do not edit.',
       '// CRC Handbook of Chemistry and Physics, 84th ed.: dissociation constants at 25 °C.',
       "part of 'acids.dart';", '', 'const List<AcidData> acidTable = [']
for line in open('tool/data/crc_pka.tsv', encoding='utf-8'):
    if line.startswith('#') or not line.strip():
        continue
    kind, name, formula, pk = line.rstrip('\n').split('\t')
    formula = FORMULA.get(name, formula)
    values = [float(v) for v in pk.split()]
    if kind == 'base':
        (pkb,) = values
        out.append("  AcidData(Bi('%s', '%s'), '%s', [%s], isBase: true, pKb: %s),"
                   % (name, TR[name], formula, repr(round(14.0 - pkb, 4)), repr(pkb)))
    else:
        out.append("  AcidData(Bi('%s', '%s'), '%s', [%s]),"
                   % (name, TR[name], formula, ', '.join(repr(v) for v in values)))
out.append('];')
open('lib/core/acid_data.dart', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(len(out) - 6, 'entries')
