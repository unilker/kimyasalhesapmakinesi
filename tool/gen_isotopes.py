"""Generates lib/core/chem/isotopes_data.dart from tool/data/nist_isotopes.tsv.

  python3 tool/gen_isotopes.py
"""
import collections

iso = collections.OrderedDict()
for line in open('tool/data/nist_isotopes.tsv'):
    if line.startswith('#') or not line.strip():
        continue
    z, sym, a, m, c = line.split('\t')
    iso.setdefault(sym, []).append((int(a), m.strip(), c.strip()))

out = ['// GENERATED by tool/gen_isotopes.py from tool/data/nist_isotopes.tsv – do not edit.',
       '// NIST Atomic Weights and Isotopic Compositions: (mass number, relative atomic',
       '// mass in u, representative isotopic composition as a mole fraction).',
       '',
       'const Map<String, List<(int, double, double)>> naturalIsotopes = {']
for sym, lst in iso.items():
    total = sum(float(c) for _, _, c in lst)
    if abs(total - 1) > 2e-4:
        raise SystemExit('%s abundances sum to %r' % (sym, total))
    out.append("  '%s': [%s]," % (sym, ', '.join('(%d, %s, %s)' % t for t in lst)))
out.append('};')
open('lib/core/chem/isotopes_data.dart', 'w').write('\n'.join(out) + '\n')
print(len(iso), 'elements')
