"""Generates lib/core/nmr_data.dart from tool/data/iupac_nmr.tsv.

  python3 tool/gen_nmr.py

The rows were checked against the text of the paper: for every nucleus
exactly one table line contains its abundance, magnetogyric ratio and Xi.
"""
out = ['// GENERATED by tool/gen_nmr.py from tool/data/iupac_nmr.tsv – do not edit.',
       '// IUPAC Recommendations 2001 (Harris et al., Pure Appl. Chem. 73, 1795).',
       "part of 'nmr.dart';", '', 'const List<NmrNucleus> nmrNuclei = [']
for line in open('tool/data/iupac_nmr.tsv', encoding='utf-8'):
    if line.startswith('#') or not line.strip():
        continue
    a, sym, spin, ab, g, xi, ref = line.rstrip('\n').split('\t')
    num, _, den = spin.partition('/')
    twice = int(num) * (2 // int(den)) if den else 2 * int(num)
    out.append("  NmrNucleus(%s, '%s', %d, %r, %r, %r, '%s')," % (
        a, sym, twice, float(ab), float(g.replace(' ', '')), float(xi.replace(' ', '')), ref))
out.append('];')
open('lib/core/nmr_data.dart', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(len(out) - 6, 'nuclei')
