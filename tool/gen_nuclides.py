"""Generates lib/core/nuclide_data.dart from tool/data/nubase2020_selected.txt.

  python3 tool/gen_nuclides.py

Columns follow the NUBASE2020 format description. Atomic masses are
A + (mass excess + excitation energy) / 931494.10242 keV (the AME2020
value of u).
"""
import re

U_KEV = 931494.10242
UNITS = ['ys', 'zs', 'as', 'fs', 'ps', 'ns', 'us', 'ms', 's', 'm', 'h', 'd', 'y', 'ky', 'My', 'Gy', 'Ty', 'Py', 'Ey']

out = ['// GENERATED by tool/gen_nuclides.py from tool/data/nubase2020_selected.txt – do not edit.',
       '// NUBASE2020 (Kondev et al., Chin. Phys. C 45, 030001, 2021).',
       "part of 'nuclides.dart';", '', 'const List<NuclideData> nuclideTable = [']
for line in open('tool/data/nubase2020_selected.txt'):
    if line.startswith('#') or not line.strip():
        continue
    a = int(line[0:3])
    z = int(line[4:7])
    name = line[11:16].strip()
    symbol = re.sub(r'^\d+', '', name)
    isomer = line[16].strip()
    excess = float(line[18:31].replace('#', ''))
    exc = line[42:54].strip().replace('#', '')
    excess += float(exc) if exc else 0.0
    t, unit, dt = line[69:78].strip(), line[78:80].strip(), line[81:88].strip()
    if '#' in t or unit not in UNITS:
        raise SystemExit('unexpected half-life for ' + name)
    br = line[119:209].strip()
    modes, abundance = [], None
    for part in br.split(';'):
        part = part.strip()
        m = re.match(r'^([A-Za-z0-9+\-]+)\s*([=~<>])\s*([\d.eE+-]+)', part)
        if not m:
            continue
        key, rel, val = m.groups()
        if key == 'IS':
            abundance = float(val)
            continue
        modes.append("('%s', '%s', %s)" % (key, rel, repr(float(val))))
    mass = a + excess / U_KEV
    out.append("  NuclideData('%s', %d, %d, '%s', %s, '%s', '%s', '%s', [%s], %s),"
               % (symbol, a, z, isomer, repr(mass), t, unit, dt, ', '.join(modes),
                  'null' if abundance is None else repr(abundance)))
out.append('];')
open('lib/core/nuclide_data.dart', 'w').write('\n'.join(out) + '\n')
print(len(out) - 6, 'nuclides')
